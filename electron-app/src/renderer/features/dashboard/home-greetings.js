/** 현재 시각으로 시간대 코드 반환 */
function _bandFor(date){
  const h=(date||new Date()).getHours();
  if(h>=8&&h<10)return 'm';   /* 아침 */
  if(h>=10&&h<12)return 'f';  /* 오전 몰입 */
  if(h>=12&&h<13)return 'l';  /* 점심 */
  if(h>=13&&h<15)return 'a';  /* 오후 나른 */
  if(h>=15&&h<17)return 'w';  /* 마무리 */
  if(h>=17&&h<22)return 'e';  /* 저녁 */
  return 'n';                   /* 야간 */
}

/** 시간대 자동 + 무작위 인사말 1개 */
let _greetLastBand='', _greetLastMsg='';
export function getGreeting(date){
  const band=_bandFor(date);
  /* 같은 시간대(band)면 인사말 고정 — 재렌더(캘린더 입력 등)마다 바뀌지 않도록 캐시. band 바뀌면 새로 뽑음. (2026-07-02) */
  if(band===_greetLastBand && _greetLastMsg) return _greetLastMsg;
  const pool=GREETINGS[band]||GREETINGS.m;
  _greetLastMsg = pool[Math.floor(Math.random()*pool.length)];
  _greetLastBand = band;
  return _greetLastMsg;
}

