export const REPORT_LABELS = { 1: '즉시', 2: '24시간 이내', 3: '24시간 이내', 4: '7일 이내' };

function topic(name) {
  const text = String(name || '').trim();
  const code = text.charCodeAt(text.length - 1);
  const batchim = code >= 0xac00 && code <= 0xd7a3 && (code - 0xac00) % 28 !== 0;
  return text + (batchim ? '은' : '는');
}

export function diseaseDetailUrl(name) {
  return 'https://www.kdca.go.kr/search.do?category=TOTAL&kwd=' + encodeURIComponent(String(name || '').trim());
}

export function diseaseBrief(disease) {
  if (BRIEFS[disease.name]) return BRIEFS[disease.name];
  const group = GROUP_LINES[disease.group];
  if (group) return topic(disease.name) + ' ' + group;
  const when = REPORT_LABELS[disease.grade] || '지침에 적힌 기한';
  return topic(disease.name) + ' 감염병예방법상 제' + disease.grade + '급 감염병입니다. 신고는 ' + when + '이며, 증상과 격리·등교 기준은 공식 자료를 확인합니다.';
}
