"""Import a reviewed KDCA public legal-disease HTML snapshot (no runtime scraping).

Usage: python scripts/import-infectious-catalog.py downloaded.html YYYY-MM-DD
Review the generated diff and guidance sources before shipping a new snapshot.
"""
import html
import json
import re
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text(encoding="utf-8-sig")
checked = sys.argv[2]
assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", checked)
rows = []
clean = lambda s: re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]*>", " ", s))).strip()
for table in re.findall(r"<table\b[^>]*>(.*?)</table>", source, re.S | re.I):
    grade = re.search(r"<caption>\s*([1-4])급별리스트", table)
    if not grade:
        continue
    for tr in re.findall(r"<tr\b[^>]*>(.*?)</tr>", table, re.S | re.I):
        cells = re.findall(r"<td\b[^>]*>(.*?)</td>", tr, re.S | re.I)
        if len(cells) < 2:
            continue
        name = re.search(r'<a\b[^>]*data-icdCd="([^"]+)"[^>]*>(.*?)</a>', cells[0], re.S | re.I)
        if not name:
            continue
        full_name = clean(name[2])
        group = re.match(r"^\(([^)]+)\)\s*(.+)$", full_name)
        entry = dict(id=f"kdca-{len(rows)+1}", name=group[2] if group else full_name,
                     grade=int(grade[1]), kcd=clean(cells[1]))
        if group:
            entry['group'] = group[1]
        rows.append(entry)
assert len(rows) >= 120, f"Incomplete catalog: {len(rows)}"
assert len({r['name'] for r in rows}) == len(rows), "Duplicate disease names"
dest = Path(__file__).resolve().parents[1] / "src/renderer/core/infectious-catalog-data.js"
dest.write_text("/* KDCA public legal-disease list. Factual names/classifications/codes; source attribution below.\n"
                " * Generated by scripts/import-infectious-catalog.py; review before updating. */\n"
                f"export const CATALOG_CHECKED_AT = '{checked}';\n"
                "export const CATALOG_SOURCE = 'https://dportal.kdca.go.kr/pot/ii/sttyInftnsds/sttyInftnsds.do';\n"
                "export const INFECTIOUS_CATALOG = " + json.dumps(rows, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
print(f"Imported {len(rows)} entries: " + str({g: sum(r['grade'] == g for r in rows) for g in range(1, 5)}))
